
.ORIG x5000

ST R7, OUT_SAVE_R7
ST R0, OUT_SAVE_R0
ST R1, OUT_SAVE_R1
ST R2, OUT_SAVE_R2
ST R3, OUT_SAVE_R3

ADD R1, R0, #0
AND R2, R2, #0

; Calculate tens digit
TENS_LOOP
ADD R3, R1, #-10
BRn PRINT_DIGITS
ADD R1, R3, #0
ADD R2, R2, #1
BRnzp TENS_LOOP

; Print tens digit
PRINT_DIGITS
LD R3, ASCII_ZERO
ADD R0, R2, R3
OUT

; Print ones digit
LD R3, ASCII_ZERO
ADD R0, R1, R3
OUT

; Restore registers
LD R0, OUT_SAVE_R0
LD R1, OUT_SAVE_R1
LD R2, OUT_SAVE_R2
LD R3, OUT_SAVE_R3
LD R7, OUT_SAVE_R7

RET

ASCII_ZERO  .FILL #48
OUT_SAVE_R7 .BLKW #1
OUT_SAVE_R0 .BLKW #1
OUT_SAVE_R1 .BLKW #1
OUT_SAVE_R2 .BLKW #1
OUT_SAVE_R3 .BLKW #1

.END
